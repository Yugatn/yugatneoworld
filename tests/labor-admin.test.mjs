import assert from "node:assert/strict";
import {applyLaborCommand} from "../server/labor-admin.js";
import {publicVacancies} from "../server/labor-store.js";
const s={version:1,organizations:[{id:"org1",name:"Test employer",status:"verified"},{id:"org2",name:"Other employer",status:"verified"}],vacancies:[]};
const actor={id:"staff1",organizationId:"org1",role:"recruiter",active:true};
const create={type:"vacancy.create",vacancy:{organizationId:"org1",title:"Accountant",description:"Prepare monthly accounts and reports",location:"Remote"}};
const created=applyLaborCommand(s,actor,create);
assert.equal(created.snapshot.vacancies[0].status,"draft");
assert.equal(s.vacancies.length,0);
assert.equal(publicVacancies(created.snapshot).length,0);
const id=created.event.recordId;
const opened=applyLaborCommand(created.snapshot,actor,{type:"vacancy.update",vacancyId:id,patch:{status:"open"}});
assert.equal(publicVacancies(opened.snapshot).length,1);
assert.throws(()=>applyLaborCommand(opened.snapshot,{...actor,organizationId:"org2"},{type:"vacancy.close",vacancyId:id}),/vacancy_not_found/);
assert.throws(()=>applyLaborCommand(s,{...actor,active:false},create),/unauthorized/);
assert.throws(()=>applyLaborCommand(s,actor,{...create,vacancy:{...create.vacancy,organizationId:"org2"}}),/invalid_vacancy/);
assert.throws(()=>applyLaborCommand(opened.snapshot,actor,{type:"vacancy.update",vacancyId:id,patch:{organizationId:"org2"}}),/invalid_patch/);
assert.equal(applyLaborCommand(opened.snapshot,actor,{type:"vacancy.close",vacancyId:id}).snapshot.vacancies[0].status,"closed");
console.log("labor admin tests passed");
