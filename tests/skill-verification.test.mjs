import assert from "node:assert/strict";
import { generateKeyPairSync } from "node:crypto";
import { validateAttestation, skillStatus, skillSummary } from "../src/domain-ts/skill-verification.js";
import { digestEvidence, signAttestation, verifyAttestationSignature } from "../server/skill-crypto.js";
const hash = digestEvidence("redacted-evidence");
const base = { id:"a1", employeeId:"employee", organizationId:"company", skillId:"excel", issuerId:"director", issuerRole:"director", issuerAuthorized:true, employment:{source:"employer_record",referenceHash:hash,verified:true,employeeId:"employee",organizationId:"company",startDate:"2023-01-01"},evidence:[{kind:"task_record",referenceHash:hash,verified:true}],issuedAt:"2025-01-01",reviewDueAt:"2027-01-01",signatureVerified:true };
assert.deepEqual(validateAttestation(base),[]);
assert.equal(skillStatus(base,"2026-10-23"),"verified_current");
assert.equal(skillStatus(base,"2027-02-01"),"review_due");
assert.equal(skillStatus({...base,issuerAuthorized:false},"2026-10-23"),"unverified");
assert.equal(skillStatus({...base,disputed:true},"2026-10-23"),"disputed");
assert.equal(skillStatus({...base,revokedAt:"2026-02-01"},"2026-10-23"),"revoked");
assert.equal(skillSummary([base],"employee","2026-10-23")[0].confirmations,1);
const {publicKey,privateKey}=generateKeyPairSync("ed25519");
const record={id:"a1",employeeId:"employee",organizationId:"company",skillId:"excel",issuerId:"director",issuedAt:"2025-01-01",reviewDueAt:"2027-01-01",evidenceHash:hash};
const signature=signAttestation(record,privateKey);
assert.equal(verifyAttestationSignature(record,signature,publicKey),true);
assert.equal(verifyAttestationSignature({...record,skillId:"1c"},signature,publicKey),false);
assert.equal(verifyAttestationSignature(record,"forged",publicKey),false);
console.log("skill verification tests passed");
