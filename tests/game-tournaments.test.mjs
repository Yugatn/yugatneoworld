import assert from "node:assert/strict";
import { GAME_CATALOG, createTournament, addParticipant, createSingleEliminationRounds } from "../src/domain/game-tournaments.js";
assert.equal(GAME_CATALOG.chess.status, "planned");
assert.equal(GAME_CATALOG["tic-tac-toe"].status, "playable-local");
const t = createTournament({ name: "Autumn Cup", game: "chess", format: "single-elimination", player: "Yugatn" }, 100, "t1");
assert.equal(t.createdAt, 100);
assert.equal(t.participants.length, 1);
assert.equal(t.persistence, "local-only");
assert.throws(() => createTournament({ name: "x", game: "bad", format: "round-robin", player: "a" }));
assert.throws(() => createTournament({ name: " ", game: "chess", format: "round-robin", player: "a" }));
const joined = addParticipant(t, { id: "p2", name: "Player 2" });
assert.equal(joined.participants.length, 2);
assert.equal(addParticipant(joined, { id: "p2", name: "Duplicate" }).participants.length, 2);
assert.throws(() => addParticipant({ ...t, status: "finished" }, { id: "p3", name: "Player 3" }));
const rounds = createSingleEliminationRounds([{ id: "1", name: "A" }, { id: "2", name: "B" }, { id: "3", name: "C" }]);
assert.equal(rounds.length, 2);
assert.equal(rounds[0].length, 2);
assert.equal(rounds[0][1].bye, true);
assert.equal(rounds[0][1].winnerId, "3");
assert.deepEqual(createSingleEliminationRounds([]), []);
console.log("game tournament tests OK");
