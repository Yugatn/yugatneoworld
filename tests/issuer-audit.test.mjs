import assert from "node:assert/strict";
import {generateKeyPairSync} from "node:crypto";
import {authorizeIssuer,checkIssuerSignature} from "../server/issuer-registry.js";
import {appendAuditEvent,verifyAuditChain} from "../server/audit-ledger.js";
import {digestEvidence,signAttestation,verifyAttestationSignature} from "../server/skill-crypto.js";
const {publicKey,privateKey}=generateKeyPairSync("ed25519");
const claim={id:"a",employeeId:"e",organizationId:"org",skillId:"excel",issuerId:"manager",issuerRole:"supervisor",issuedAt:"2026-01-01",reviewDueAt:"2027-01-01",evidenceHash:digestEvidence("work")};
const grants=[{issuerId:"manager",organizationId:"org",role:"supervisor",status:"active",skills:["excel"],validFrom:"2025-01-01"}];
const keys=[{issuerId:"manager",organizationId:"org",status:"active",validFrom:"2025-01-01",publicKey}];
const signature=signAttestation(claim,privateKey);
const check=(c=claim,g=grants,k=keys,s=signature)=>checkIssuerSignature({grants:g,claim:c,keys:k,signature:s,verifySignature:verifyAttestationSignature});
assert.equal(check().valid,true);
assert.equal(check({...claim,skillId:"1c"}).valid,false);
assert.equal(check(claim,[{...grants[0],revokedAt:"2025-12-01"}]).valid,false);
assert.equal(check(claim,grants,[{...keys[0],status:"revoked"}]).valid,false);
assert.equal(authorizeIssuer(grants,{issuerId:"manager",organizationId:"other",role:"supervisor",skillId:"excel",at:"2026-01-01"}),false);
let events=appendAuditEvent([],{type:"attestation.issued",actorId:"manager",subjectId:"e",occurredAt:"2026-01-01",referenceHash:claim.evidenceHash});
events=appendAuditEvent(events,{type:"attestation.reviewed",actorId:"auditor",subjectId:"e",occurredAt:"2026-02-01",referenceHash:claim.evidenceHash});
assert.equal(verifyAuditChain(events),true);
assert.equal(verifyAuditChain(events.map((x,i)=>i?{...x,actorId:"attacker"}:x)),false);
console.log("issuer and audit tests passed");
